"""Complete MCC truth table for the critical module Check.get_status (Phase 5).

Every test case is named after its row of the truth table
(`evidence/raw/get-status-truth-table.csv`, row id = R + the 7 condition bits
A1..A7 in evaluation order, see docs/08-unit-testing.md section 3):

    A1 last_start is set          A5 grace_start is None (next elapse never)
    A2 now >= last_start + grace  A6 now >= grace_end
    A3 with_started is true       A7 now >= grace_start
    A4 stored status in (new, paused, down)

The table is generated by tools/unit/get_status_truth_table.py directly from
business rule BR-02 (docs/01 section 6) - run scripts/run-unit-tests.ps1, which
regenerates it before pytest, so tests and table can never drift apart.

D1 (master prompt): the status logic lives on the Check model, so these tests
call Check.get_status() directly on an unsaved Check() - no DB - with frozen
time (time_machine), never sleeping.  No production code is modified.

Covers FR-10 / BR-02 (traceability rows T-UNIT-BR02-*).
"""
from __future__ import annotations

import csv
from datetime import datetime, timedelta as td, timezone
from pathlib import Path

import pytest
import time_machine

from hc.api.models import Check

REPO_ROOT = Path(__file__).resolve().parents[3]
TABLE_CSV = REPO_ROOT / "evidence" / "raw" / "get-status-truth-table.csv"
PAIRS_CSV = REPO_ROOT / "evidence" / "raw" / "get-status-mcdc-pairs.csv"

# Frozen clock for every case in this module: no sleeping anywhere.
NOW = datetime(2026, 11, 24, 12, 0, 0, tzinfo=timezone.utc)
GRACE = td(hours=1)   # default grace in the app; all values >= BR-01 minimum (60)
TIMEOUT = td(days=1)  # default timeout in the app

CONDITIONS = ("a1", "a2", "a3", "a4", "a5", "a6", "a7")


def _load_rows() -> list[dict[str, str]]:
    if not TABLE_CSV.exists():
        raise RuntimeError(
            f"{TABLE_CSV} not found - run: python tools/unit/get_status_truth_table.py"
        )
    with TABLE_CSV.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


ROWS = _load_rows()

# Cases carry their row id as the pytest case id (test name = truth-table row).
# The 8 rows of the minimal MC/DC set (n + 1) are marked so `pytest -m mcdc`
# runs exactly that set.
CASES = [
    pytest.param(
        row,
        id=row["row_id"],
        marks=pytest.mark.mcdc if row["mcdc_condition"] else (),
    )
    for row in ROWS
]


def _realization(row: dict[str, str]) -> tuple[Check, bool]:
    """Build a concrete (Check, with_started) state for one truth-table row.

    Only the row's *evaluated* conditions constrain the state; masked
    conditions are don't-care and are filled with harmless defaults.
    Witnesses per path (see docs/08 section 3.3):
      A1/A2  last_start = NOW (A2 false) or NOW - 2*grace (A2 true), else None
      A4     status "new" if A4 true, else "up"
      A5     true : kind=oncalendar with a schedule that has no next
                    occurrence ("2020-01-01 00:00:00", last_ping in 2026)
      A5/A6/A7 false: simple kind, last_ping = grace_start - timeout with
                    grace_start = NOW - 2*grace (A6 true),
                                  NOW - grace/2 (A6 false, A7 true),
                                  NOW + grace     (A6 false, A7 false)
    """
    a = {name: row[name] == "1" for name in CONDITIONS}

    check = Check(kind="simple", status="up", timeout=TIMEOUT, grace=GRACE, tz="UTC")

    if a["a1"]:
        check.last_start = NOW - (2 * GRACE if a["a2"] else td(0))
    else:
        check.last_start = None

    with_started = a["a3"]
    check.status = "new" if a["a4"] else "up"

    if not a["a4"]:
        if a["a5"]:
            check.kind = "oncalendar"
            check.schedule = "2020-01-01 00:00:00"
            check.last_ping = NOW
        elif a["a6"]:
            check.last_ping = (NOW - 2 * GRACE) - TIMEOUT
        elif a["a7"]:
            check.last_ping = (NOW - GRACE // 2) - TIMEOUT
        else:
            check.last_ping = (NOW + GRACE) - TIMEOUT

    return check, with_started


@pytest.mark.parametrize("row", CASES)
def test_FR10_BR02_get_status_mcc_row(row: dict[str, str]) -> None:
    """One case per truth-table row: real get_status() vs the table's outcome."""
    check, with_started = _realization(row)
    with time_machine.travel(NOW, tick=False):
        result = check.get_status(with_started=with_started)
    assert result == row["outcome"], (
        f"{row['row_id']}: expected {row['outcome']!r}, got {result!r} "
        f"(evaluated={row['evaluated']})"
    )


def test_FR10_BR02_truth_table_is_complete() -> None:
    """Guard: the MCC artifact itself (2^n rows, classification, MC/DC set)."""
    # Complete table: 2^7 = 128 rows in order, every row classified.
    assert len(ROWS) == 128
    assert [row["row_id"] for row in ROWS] == [f"R{n:07b}" for n in range(128)]
    assert all(row["feasible"] == "yes" for row in ROWS)
    # No silent pragma: masked conditions are recorded per row, not deleted.
    assert all(row["evaluated"] for row in ROWS)

    # MC/DC set: n + 1 = 8 distinct rows, 7 pairs, each pair differs in
    # exactly its one condition and flips the outcome, all conditions covered.
    with PAIRS_CSV.open(newline="", encoding="utf-8") as handle:
        pairs = list(csv.DictReader(handle))
    assert len(pairs) == 7
    assert sorted(pair["condition"] for pair in pairs) == sorted(CONDITIONS)

    by_id = {row["row_id"]: row for row in ROWS}
    mcdc_rows: set[str] = set()
    for pair in pairs:
        true_row = by_id[pair["row_true"]]
        false_row = by_id[pair["row_false"]]
        condition = pair["condition"]
        diffs = [name for name in CONDITIONS if true_row[name] != false_row[name]]
        assert diffs == [condition], f"{condition}: pair differs in {diffs}"
        assert true_row[condition] == "1" and false_row[condition] == "0"
        assert true_row["outcome"] != false_row["outcome"], condition
        mcdc_rows.update((pair["row_true"], pair["row_false"]))
    assert len(mcdc_rows) == 8

    # The marker set used by `pytest -m mcdc` matches the table's MC/DC column.
    marked = {row["row_id"] for row in ROWS if row["mcdc_condition"]}
    assert marked == mcdc_rows
