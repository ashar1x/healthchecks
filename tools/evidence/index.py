"""Generate evidence/manifest.csv from files under evidence/.

One row per artefact: ID, description, path, producing command, tool and
version, UTC timestamp, git commit and SHA-256. The CSV is machine-generated;
nobody edits it by hand.
"""
from __future__ import annotations

import csv
import hashlib
import subprocess
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "evidence"
OUT = EVIDENCE / "manifest.csv"

TOOLS = {
    "raw/get-status-truth-table.csv": ("python tools/unit/get_status_truth_table.py", "Python 3.12"),
    "raw/get-status-mcdc-pairs.csv": ("python tools/unit/get_status_truth_table.py", "Python 3.12"),
    "raw/requirements-coverage.json": ("python tools/traceability/coverage.py --pytest-report evidence/raw/pytest-report.json", "Python 3.12"),
    "raw/pytest-report.json": ("pytest --json-report", "pytest 9.2.0"),
    "raw/pareto.json": ("python tools/evidence/pareto.py", "Python 3.12"),
    "raw/pareto.svg": ("python tools/evidence/pareto.py", "Python 3.12"),
    "raw/issues.json": ("gh api repos/ashar1x/healthchecks/issues?state=all", "gh 2.x"),
    "mutation/mutmut-summary.json": ("python tools/mutation/score_gate.py", "mutmut 3.8.1"),
    "mutation/custom-operators.json": ("python tools/mutation/custom_operators.py", "mutmut 3.8.1"),
    "mutation/survivor-diffs.txt": ("mutmut results | mutmut show", "mutmut 3.8.1"),
    "security/access-matrix.md": ("npx playwright test tests/e2e/access-control.spec.js", "Playwright 1.65.1"),
    "security/access-matrix.json": ("npx playwright test tests/e2e/access-control.spec.js", "Playwright 1.65.1"),
    "security/zap-alerts.json": ("ZAP 2.17 passive via proxied Playwright", "OWASP ZAP 2.17.0"),
    "security/pip-audit.json": ("pip-audit -r requirements.txt -r requirements-dev.txt --format json", "pip-audit 2.10.1"),
    "security/npm-audit.json": ("npm audit --json", "npm 10.9.9"),
    "phase9": ("npx playwright test / node tests/e2e/lighthouse.js", "Lighthouse 13.6.0 / axe 4.14.1"),
    "performance": ("k6 run tests/k6/load.js --summary-export", "k6 2.3.0"),
    "screenshots": ("node tools/evidence/screenshots.mjs", "Playwright 1.65.1"),
}


@dataclass(frozen=True, slots=True)
class Row:
    identifier: str
    description: str
    path: str
    command: str
    tool: str
    timestamp: str
    commit: str
    sha256: str
    captured_by: str


def describe(relative: str) -> tuple[str, str]:
    for key, value in TOOLS.items():
        if relative == key or relative.startswith(key):
            return value
    return ("generated by project scripts", "project toolchain")


def git_commit() -> str:
    return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def collect() -> list[Row]:
    now = datetime.now(timezone.utc).isoformat()
    commit = git_commit()
    rows: list[Row] = []
    for path in sorted(EVIDENCE.rglob("*")):
        if not path.is_file() or path.name == "manifest.csv":
            continue
        relative = path.relative_to(ROOT).as_posix()
        command, tool = describe(relative.removeprefix("evidence/"))
        rows.append(
            Row(
                identifier=f"EV-{len(rows) + 1:03d}",
                description=path.stem.replace("-", " "),
                path=relative,
                command=command,
                tool=tool,
                timestamp=now,
                commit=commit,
                sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                captured_by="Ali Haider Bajwa (24i-3102)",
            )
        )
    return rows


def main() -> int:
    rows = collect()
    with OUT.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["id", "description", "path", "command", "tool_version", "utc_timestamp", "git_commit", "sha256", "captured_by"])
        for row in rows:
            writer.writerow([row.identifier, row.description, row.path, row.command, row.tool, row.timestamp, row.commit, row.sha256, row.captured_by])
    print(f"manifest: {len(rows)} artefacts -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
